package com.hotel4you.hotel4you.DAO;

import com.hotel4you.hotel4you.DAO.db.DBConnection;
import com.hotel4you.hotel4you.Model.Utilizador;
import com.hotel4you.hotel4you.Model.enums.Perfil;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Testes do {@link UtilizadorDAOSQL} contra uma base de dados H2 <b>em memória</b>, criada só para os
 * testes. Nunca se liga ao SQL Server do ISEP: antes de cada teste confirma-se que a ligação é mesmo
 * à H2 (uma variável de ambiente {@code HOTEL4YOU_DB_URL} podia desviar a ligação para outro sítio).
 * A tabela é criada aqui (sem passar pelos scripts de {@code DATABASE/}) com o mesmo nome e colunas
 * que o DAO usa; o username é {@code VARCHAR_IGNORECASE} para imitar a collation do SQL Server.
 */
class UtilizadorDAOSQLTest {

    private static final String URL_H2 = "jdbc:h2:mem:hotel4you_utilizadores_teste;DB_CLOSE_DELAY=-1";

    private static Path configuracaoDeTeste;
    private static String configuracaoAnterior;

    private UtilizadorDAOSQL dao;

    @BeforeAll
    static void apontarOsTestesParaAH2() throws Exception {
        configuracaoDeTeste = Files.createTempFile("hotel4you-teste-", ".properties");
        Files.writeString(configuracaoDeTeste, "db.url=" + URL_H2 + System.lineSeparator(), StandardCharsets.UTF_8);
        configuracaoAnterior = System.getProperty(DBConnection.PROPRIEDADE_FICHEIRO);
        System.setProperty(DBConnection.PROPRIEDADE_FICHEIRO, configuracaoDeTeste.toString());
        DBConnection.recarregarConfiguracao();
    }

    @AfterAll
    static void repor() throws Exception {
        if (configuracaoAnterior == null) {
            System.clearProperty(DBConnection.PROPRIEDADE_FICHEIRO);
        } else {
            System.setProperty(DBConnection.PROPRIEDADE_FICHEIRO, configuracaoAnterior);
        }
        DBConnection.recarregarConfiguracao();
        Files.deleteIfExists(configuracaoDeTeste);
    }

    @BeforeEach
    void criarTabelasVazias() throws SQLException {
        try (Connection conn = DBConnection.getConnection(); Statement st = conn.createStatement()) {
            String url = conn.getMetaData().getURL();
            assertTrue(url.startsWith("jdbc:h2:mem:"), "os testes só podem usar a H2 em memória, mas ligou a " + url);

            st.execute("CREATE SCHEMA IF NOT EXISTS dbo");
            st.execute("DROP TABLE IF EXISTS dbo.Fornecedor");
            st.execute("DROP TABLE IF EXISTS dbo.Utilizador");
            st.execute("CREATE TABLE dbo.Utilizador ("
                    + "IdUtilizador INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "Username VARCHAR_IGNORECASE(50) NOT NULL UNIQUE, "
                    + "PasswordHash VARCHAR(255) NOT NULL, "
                    + "Nome VARCHAR(100) NOT NULL, "
                    + "Perfil VARCHAR(30) NOT NULL, "
                    + "Ativo BOOLEAN DEFAULT TRUE NOT NULL)");
            st.execute("CREATE TABLE dbo.Fornecedor ("
                    + "IdFornecedor INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "IdUtilizador INT REFERENCES dbo.Utilizador (IdUtilizador))");
        }
        dao = new UtilizadorDAOSQL();
    }

    private Utilizador inserir(String username, Perfil perfil) {
        return dao.inserir(Utilizador.novo(username, "password1", "Nome de " + username, perfil));
    }

    @Test
    void inserirAtribuiOIdGeradoPelaBaseDeDados() {
        Utilizador ana = inserir("ana", Perfil.RECECIONISTA);
        Utilizador rui = inserir("rui", Perfil.GESTOR);

        assertTrue(ana.getId() > 0);
        assertTrue(rui.getId() > ana.getId());
    }

    @Test
    void utilizadorLidoTemOsMesmosDadosEAPasswordSoEmHash() {
        Utilizador gravado = inserir("ana", Perfil.EMPRESA_RESTAURACAO);

        Utilizador lido = dao.procurarPorId(gravado.getId()).orElseThrow();

        assertEquals("ana", lido.getUsername());
        assertEquals("Nome de ana", lido.getNome());
        assertEquals(Perfil.EMPRESA_RESTAURACAO, lido.getPerfil());
        assertTrue(lido.isAtivo());
        assertEquals(gravado.getPasswordHash(), lido.getPasswordHash());
        assertFalse(lido.getPasswordHash().contains("password1"));
        assertTrue(lido.verificarPassword("password1"));
        assertFalse(lido.verificarPassword("outra"));
    }

    @Test
    void todosOsPerfisSaoGuardadosELidosCorretamente() {
        for (Perfil perfil : Perfil.values()) {
            Utilizador gravado = inserir("u_" + perfil.name(), perfil);
            assertEquals(perfil, dao.procurarPorId(gravado.getId()).orElseThrow().getPerfil());
        }
    }

    @Test
    void procurarPorUsernameNaoDistingueMaiusculasEIgnoraEspacos() {
        Utilizador ana = inserir("Ana", Perfil.RECECIONISTA);

        assertEquals(ana.getId(), dao.procurarPorUsername("ana").orElseThrow().getId());
        assertEquals(ana.getId(), dao.procurarPorUsername("ANA").orElseThrow().getId());
        assertEquals(ana.getId(), dao.procurarPorUsername("  ana  ").orElseThrow().getId());
    }

    @Test
    void procurarDevolveVazioSeNaoExisteOuSeOUsernameForNulo() {
        inserir("ana", Perfil.RECECIONISTA);

        assertTrue(dao.procurarPorUsername("outro").isEmpty());
        assertTrue(dao.procurarPorUsername(null).isEmpty());
        assertTrue(dao.procurarPorId(9999).isEmpty());
    }

    @Test
    void usernameDuplicadoDaMensagemClaraENaoFicaGuardado() {
        inserir("ana", Perfil.RECECIONISTA);

        DAOException erro = assertThrows(DAOException.class, () -> inserir("ANA", Perfil.GESTOR));

        assertTrue(erro.getMessage().contains("Já existe um utilizador"), erro.getMessage());
        assertEquals(1, dao.listarTodos().size());
    }

    @Test
    void listarTodosDevolveTodosPorOrdemDeId() {
        Utilizador primeiro = inserir("zeca", Perfil.GESTOR);
        Utilizador segundo = inserir("ana", Perfil.RECECIONISTA);
        Utilizador terceiro = inserir("rui", Perfil.FORNECEDOR);

        List<Utilizador> todos = dao.listarTodos();

        assertEquals(List.of(primeiro.getId(), segundo.getId(), terceiro.getId()),
                todos.stream().map(Utilizador::getId).toList());
    }

    @Test
    void atualizarGuardaNomePerfilPasswordEEstadoAtivo() {
        Utilizador ana = inserir("ana", Perfil.RECECIONISTA);
        ana.setNome("Ana Maria");
        ana.setPerfil(Perfil.GESTOR);
        ana.setAtivo(false);
        ana.alterarPassword("novaPassword");

        dao.atualizar(ana);

        Utilizador lido = dao.procurarPorId(ana.getId()).orElseThrow();
        assertEquals("Ana Maria", lido.getNome());
        assertEquals(Perfil.GESTOR, lido.getPerfil());
        assertFalse(lido.isAtivo());
        assertTrue(lido.verificarPassword("novaPassword"));
        assertFalse(lido.verificarPassword("password1"));
        assertEquals("ana", lido.getUsername(), "o username não muda");
    }

    @Test
    void atualizarUtilizadorInexistenteFalha() {
        Utilizador fantasma = Utilizador.novo("fantasma", "password1", "Fantasma", Perfil.GESTOR);
        fantasma.setId(9999);

        DAOException erro = assertThrows(DAOException.class, () -> dao.atualizar(fantasma));

        assertTrue(erro.getMessage().contains("não existe"));
    }

    @Test
    void removerApagaOUtilizador() {
        Utilizador ana = inserir("ana", Perfil.RECECIONISTA);

        dao.remover(ana.getId());

        assertTrue(dao.procurarPorId(ana.getId()).isEmpty());
        assertTrue(dao.listarTodos().isEmpty());
    }

    @Test
    void removerUtilizadorInexistenteFalha() {
        assertThrows(DAOException.class, () -> dao.remover(9999));
    }

    @Test
    void utilizadorComRegistosAssociadosNaoSePodeRemoverEFicaIntacto() throws SQLException {
        Utilizador fornecedor = inserir("forn", Perfil.FORNECEDOR);
        try (Connection conn = DBConnection.getConnection(); Statement st = conn.createStatement()) {
            st.execute("INSERT INTO dbo.Fornecedor (IdUtilizador) VALUES (" + fornecedor.getId() + ")");
        }

        DAOException erro = assertThrows(DAOException.class, () -> dao.remover(fornecedor.getId()));

        assertTrue(erro.getMessage().contains("desative"), erro.getMessage());
        assertTrue(dao.procurarPorId(fornecedor.getId()).isPresent());
    }
}